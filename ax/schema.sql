-- Items.
CREATE TABLE INVENTTABLE (
    ITEMID           NVARCHAR(20)  NOT NULL,
    ITEMNAME         NVARCHAR(60)  NOT NULL DEFAULT '',
    ITEMGROUPID      NVARCHAR(10)  NOT NULL DEFAULT '',
    DATAAREAID       NVARCHAR(4)   NOT NULL,
    MODIFIEDDATETIME DATETIME      NOT NULL DEFAULT GETUTCDATE(),
    RECID            BIGINT        NOT NULL PRIMARY KEY,
    CONSTRAINT I_ITEMIDX UNIQUE (DATAAREAID, ITEMID)
);

-- Inventory dimensions: where stock sits (warehouse, site, colour, size).
CREATE TABLE INVENTDIM (
    INVENTDIMID      NVARCHAR(20)  NOT NULL,
    INVENTSITEID     NVARCHAR(10)  NOT NULL DEFAULT '',
    INVENTLOCATIONID NVARCHAR(10)  NOT NULL DEFAULT '',
    INVENTCOLORID    NVARCHAR(10)  NOT NULL DEFAULT '',
    INVENTSIZEID     NVARCHAR(10)  NOT NULL DEFAULT '',
    CONFIGID         NVARCHAR(10)  NOT NULL DEFAULT '',
    DATAAREAID       NVARCHAR(4)   NOT NULL,
    RECID            BIGINT        NOT NULL PRIMARY KEY,
    CONSTRAINT I_DIMIDIDX UNIQUE (DATAAREAID, INVENTDIMID)
);

-- Current stock per item and dimension. Holds no history.
CREATE TABLE INVENTSUM (
    ITEMID           NVARCHAR(20)    NOT NULL,
    INVENTDIMID      NVARCHAR(20)    NOT NULL,
    PHYSICALINVENT   NUMERIC(28, 12) NOT NULL DEFAULT 0,
    RESERVPHYSICAL   NUMERIC(28, 12) NOT NULL DEFAULT 0,
    AVAILPHYSICAL    NUMERIC(28, 12) NOT NULL DEFAULT 0,
    ONORDER          NUMERIC(28, 12) NOT NULL DEFAULT 0,
    DATAAREAID       NVARCHAR(4)     NOT NULL,
    MODIFIEDDATETIME DATETIME        NOT NULL DEFAULT GETUTCDATE(),
    RECID            BIGINT          NOT NULL PRIMARY KEY,
    CONSTRAINT I_ITEMDIMIDX UNIQUE (DATAAREAID, ITEMID, INVENTDIMID)
);

-- Prices and discounts. RELATION 4 = sales price; ITEMCODE 0 = one item;
-- ACCOUNTCODE 2 = all customers, 0 = one customer (ACCOUNTRELATION).
CREATE TABLE PRICEDISCTABLE (
    RELATION         INT             NOT NULL,
    ITEMCODE         INT             NOT NULL,
    ITEMRELATION     NVARCHAR(20)    NOT NULL DEFAULT '',
    ACCOUNTCODE      INT             NOT NULL,
    ACCOUNTRELATION  NVARCHAR(20)    NOT NULL DEFAULT '',
    QUANTITYAMOUNT   NUMERIC(28, 12) NOT NULL DEFAULT 0,
    AMOUNT           NUMERIC(28, 12) NOT NULL DEFAULT 0,
    CURRENCY         NVARCHAR(3)     NOT NULL DEFAULT 'DKK',
    FROMDATE         DATETIME        NOT NULL DEFAULT '1900-01-01',
    TODATE           DATETIME        NOT NULL DEFAULT '1900-01-01',
    DATAAREAID       NVARCHAR(4)     NOT NULL,
    RECID            BIGINT          NOT NULL PRIMARY KEY
);

-- Customers, including B2B accounts such as insurance companies.
CREATE TABLE CUSTTABLE (
    ACCOUNTNUM       NVARCHAR(20)  NOT NULL,
    NAME             NVARCHAR(60)  NOT NULL DEFAULT '',
    CUSTGROUP        NVARCHAR(10)  NOT NULL DEFAULT '',
    CURRENCY         NVARCHAR(3)   NOT NULL DEFAULT 'DKK',
    DATAAREAID       NVARCHAR(4)   NOT NULL,
    CREATEDDATETIME  DATETIME      NOT NULL DEFAULT GETUTCDATE(),
    RECID            BIGINT        NOT NULL PRIMARY KEY,
    CONSTRAINT I_ACCOUNTIDX UNIQUE (DATAAREAID, ACCOUNTNUM)
);

-- Sales order headers.
CREATE TABLE SALESTABLE (
    SALESID          NVARCHAR(20)  NOT NULL,
    CUSTACCOUNT      NVARCHAR(20)  NOT NULL,
    SALESSTATUS      INT           NOT NULL DEFAULT 1, -- 1 open, 2 delivered, 3 invoiced, 4 cancelled
    SALESTYPE        INT           NOT NULL DEFAULT 3, -- 3 sales order
    CURRENCYCODE     NVARCHAR(3)   NOT NULL DEFAULT 'DKK',
    DATAAREAID       NVARCHAR(4)   NOT NULL,
    CREATEDDATETIME  DATETIME      NOT NULL DEFAULT GETUTCDATE(),
    RECID            BIGINT        NOT NULL PRIMARY KEY,
    CONSTRAINT I_SALESIDX UNIQUE (DATAAREAID, SALESID)
);

-- Sales order lines.
CREATE TABLE SALESLINE (
    SALESID          NVARCHAR(20)    NOT NULL,
    LINENUM          NUMERIC(28, 12) NOT NULL,
    ITEMID           NVARCHAR(20)    NOT NULL,
    INVENTDIMID      NVARCHAR(20)    NOT NULL DEFAULT '',
    SALESQTY         NUMERIC(28, 12) NOT NULL DEFAULT 0,
    SALESPRICE       NUMERIC(28, 12) NOT NULL DEFAULT 0,
    LINEAMOUNT       NUMERIC(28, 12) NOT NULL DEFAULT 0,
    SALESSTATUS      INT             NOT NULL DEFAULT 1,
    DATAAREAID       NVARCHAR(4)     NOT NULL,
    CREATEDDATETIME  DATETIME        NOT NULL DEFAULT GETUTCDATE(),
    RECID            BIGINT          NOT NULL PRIMARY KEY,
    CONSTRAINT I_SALESLINEIDX UNIQUE (DATAAREAID, SALESID, LINENUM)
);
GO
